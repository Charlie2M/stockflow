-- Products sold by the chain, identified by a unique SKU.
CREATE TABLE products (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku        VARCHAR(32)              NOT NULL,
    name       VARCHAR(120)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_products_sku UNIQUE (sku)
);

-- Physical stores, identified by a unique store code.
CREATE TABLE stores (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(16)              NOT NULL,
    name       VARCHAR(120)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_stores_code UNIQUE (code)
);

-- Current quantity of one product in one store.
-- "version" supports optimistic locking; the CHECK constraint is a last line of defence
-- that makes negative stock impossible even if application code had a bug.
CREATE TABLE stock_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id   BIGINT                   NOT NULL,
    product_id BIGINT                   NOT NULL,
    quantity   INTEGER                  NOT NULL,
    version    BIGINT                   NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_stock_items_store FOREIGN KEY (store_id) REFERENCES stores (id),
    CONSTRAINT fk_stock_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT uk_stock_items_store_product UNIQUE (store_id, product_id),
    CONSTRAINT ck_stock_items_quantity_not_negative CHECK (quantity >= 0)
);

-- Append-only ledger: every change to stock_items.quantity is recorded here.
CREATE TABLE stock_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT                   NOT NULL,
    product_id      BIGINT                   NOT NULL,
    movement_type   VARCHAR(32)              NOT NULL,
    quantity_change INTEGER                  NOT NULL,
    reference       VARCHAR(64)              NOT NULL,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_stock_movements_store FOREIGN KEY (store_id) REFERENCES stores (id),
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_stock_movements_not_zero CHECK (quantity_change <> 0)
);

CREATE INDEX idx_stock_movements_store_product ON stock_movements (store_id, product_id);

-- A request to move stock from one store to another.
CREATE TABLE transfers (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_store_id      BIGINT                   NOT NULL,
    destination_store_id BIGINT                   NOT NULL,
    status               VARCHAR(32)              NOT NULL,
    version              BIGINT                   NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    dispatched_at        TIMESTAMP WITH TIME ZONE,
    completed_at         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_transfers_source_store FOREIGN KEY (source_store_id) REFERENCES stores (id),
    CONSTRAINT fk_transfers_destination_store FOREIGN KEY (destination_store_id) REFERENCES stores (id),
    CONSTRAINT ck_transfers_different_stores CHECK (source_store_id <> destination_store_id)
);

CREATE INDEX idx_transfers_status ON transfers (status);

-- One product line inside a transfer.
CREATE TABLE transfer_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id       BIGINT  NOT NULL,
    product_id        BIGINT  NOT NULL,
    quantity          INTEGER NOT NULL,
    received_quantity INTEGER,
    CONSTRAINT fk_transfer_lines_transfer FOREIGN KEY (transfer_id) REFERENCES transfers (id),
    CONSTRAINT fk_transfer_lines_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT uk_transfer_lines_transfer_product UNIQUE (transfer_id, product_id),
    CONSTRAINT ck_transfer_lines_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_transfer_lines_received_range
        CHECK (received_quantity IS NULL OR (received_quantity >= 0 AND received_quantity <= quantity))
);
